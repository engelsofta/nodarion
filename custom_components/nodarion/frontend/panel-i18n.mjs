export function t(message, ...values) {
  const label = panelLocale === "de" ? message : english.get(message) ?? message;
  return values.length ? label.replace(/\{(\d+)\}/g, (placeholder, i) =>
    i < values.length ? String(values[i]) : placeholder) : label;
}

